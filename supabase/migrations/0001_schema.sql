create extension if not exists vector;

create table if not exists public.documents (
  id            uuid primary key,
  filename      text not null,
  page_count    integer not null default 0,
  chunk_count   integer not null default 0,
  status        text not null default 'uploaded',
  error_message text,
  is_sample     boolean not null default false,
  created_at    timestamptz not null default now()
);

create table if not exists public.chunks (
  id            bigint generated by default as identity primary key,
  document_id   uuid not null references public.documents(id) on delete cascade,
  content       text not null,
  source        text not null,
  page          integer not null,
  chunk_index   integer not null,
  total_chunks  integer not null,
  metadata      jsonb not null default '{}'::jsonb,
  embedding     vector(384)
);

create index if not exists chunks_document_id_idx on public.chunks (document_id);
create index if not exists chunks_embedding_idx
  on public.chunks using hnsw (embedding vector_cosine_ops);

-- Cosine similarity search, optionally limited to a set of documents.
create or replace function public.match_chunks(
  query_embedding vector(384),
  match_threshold float,
  match_count int,
  p_document_ids uuid[] default null
)
returns table (
  id bigint, document_id uuid, content text, source text, page int,
  chunk_index int, total_chunks int, metadata jsonb, similarity float
)
language sql stable
as $$
  select c.id, c.document_id, c.content, c.source, c.page, c.chunk_index,
         c.total_chunks, c.metadata,
         1 - (c.embedding <=> query_embedding) as similarity
  from public.chunks c
  where (p_document_ids is null or c.document_id = any(p_document_ids))
    and 1 - (c.embedding <=> query_embedding) >= match_threshold
  order by c.embedding <=> query_embedding
  limit match_count;
$$;
